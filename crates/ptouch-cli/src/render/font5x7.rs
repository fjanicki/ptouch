/// Column-major glyph: 5 bytes, bit 0 = top row. `None` outside 0x20–0x7E.
#[must_use]
pub fn glyph(c: char) -> Option<[u8; 5]> {
    let index = u32::from(c).checked_sub(0x20)?;
    let rows = ROWS.get(usize::try_from(index).ok()?)?;
    let mut cols = [0u8; 5];
    for (y, row) in rows.iter().enumerate() {
        for (x, cell) in row.bytes().enumerate() {
            if cell == b'#'
                && let Some(col) = cols.get_mut(x)
            {
                *col |= 1 << y;
            }
        }
    }
    Some(cols)
}

/// `true` if dot (`x`, `y`) of `c`'s glyph is ink (`false` outside the glyph or charset).
#[must_use]
pub fn dot(c: char, x: u32, y: u32) -> bool {
    if y >= GLYPH_HEIGHT {
        return false;
    }
    glyph(c)
        .and_then(|g| g.get(usize::try_from(x).ok()?).copied())
        .is_some_and(|col| col & (1 << y) != 0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_printable_ascii() {
        for c in ' '..='~' {
            let g = glyph(c).unwrap_or_else(|| panic!("no glyph for {c:?}"));
            assert_eq!(c == ' ', g == [0; 5], "glyph {c:?}");
            assert!(g.iter().all(|col| col & 0x80 == 0), "{c:?} taller than 7");
        }
        assert_eq!(glyph('\u{1F}'), None);
        assert_eq!(glyph('\u{7F}'), None);
        assert_eq!(glyph('é'), None);
    }

    #[test]
    fn rows_are_well_formed() {
        for rows in &ROWS {
            for row in rows {
                assert_eq!(row.len(), 5);
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'));
            }
        }
    }

    #[test]
    fn glyphs_are_distinct() {
        let all: Vec<_> = (' '..='~').map(|c| (c, glyph(c))).collect();
        for (i, (a, ga)) in all.iter().enumerate() {
            for (b, gb) in all.iter().skip(i + 1) {
                assert_ne!(ga, gb, "{a:?} and {b:?} look the same");
            }
        }
    }

    #[test]
    fn orientation_of_f() {
        // 'F': full left column, top bar.
        let g = glyph('F').unwrap();
        assert_eq!(g[0], 0x7F);
        assert!((0..5).all(|x| dot('F', x, 0)));
        assert!(!dot('F', 4, 6));
    }
}
